use burrow_github::fake::{Fake, ok};
use serde_json::{Value, json};

use super::{Door, Issue, MAX_COMMENT, asked, bounded};

fn issue(title: &str, body: Value) -> Value {
    json!({ "number": 1, "title": title, "body": body })
}

#[test]
fn what_an_issue_asks() {
    let q = |title: &str, body: Value| asked(&issue(title, body));
    assert_eq!(q("memory", json!(null)), ["memory"]);
    assert_eq!(
        q(
            "ignored",
            json!("```\nrc\n```\n<!-- a note -->\n- `queue`\n\n  units  ")
        ),
        ["rc", "queue", "units"]
    );
    assert!(q("", json!("")).is_empty());
    // A rule ends them: under it is a signature.
    assert_eq!(
        q(
            "ignored",
            json!("rc\nqueue\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_")
        ),
        ["rc", "queue"]
    );
    assert_eq!(q("memory", json!("***\nrc")), ["memory"]);
    assert_eq!(q("x", json!("rc\n-\t- -\nunits")), ["rc"]);
    // Fewer than three markers, or mixed ones, aren't a rule.
    assert_eq!(
        q("x", json!("memory\n_ _\n* *\n- -\n-*-\nunits")),
        ["memory", "_ _", "* *", "-", "-*-", "units"]
    );
}

#[test]
fn only_an_author_s_issue_is_read_and_its_refusal_names_the_door() {
    let authors = [burrow_github::fake::author("Sam")];
    let door = Door {
        repo: "sam/box",
        label: "undo",
        authors: &authors,
        what: "this machine's undo",
    };
    let mut gh = Fake::default();
    let them = Issue {
        number: 3,
        opener: "mallory".into(),
        opener_id: Some(burrow_github::fake::author("mallory").id),
    };
    assert_eq!(
        door.written(&mut gh, &them).unwrap(),
        Err("Only Sam can ask this machine's undo, so nothing was run.".into())
    );
    // Nothing was asked of GitHub for it.
    assert!(gh.asked.is_empty());
    let mut gh = Fake::default();
    gh.on("POST", "graphql", vec![ok(
        200,
        json!({ "data": { "repository": { "issue": {
            "author": burrow_github::fake::actor("sam"), "title": "t", "body": "b",
            "userContentEdits": { "totalCount": 1, "nodes": [{ "editor": burrow_github::fake::actor("mallory"), "deletedBy": null }] },
            "timelineItems": { "totalCount": 0, "nodes": [] },
        } } } }),
        &[],
    )]);
    let ours = Issue {
        number: 4,
        opener: "sam".into(),
        opener_id: Some(burrow_github::fake::author("sam").id),
    };
    let said = door.written(&mut gh, &ours).unwrap().unwrap_err();
    assert!(said.contains("changed by someone other than Sam"), "{said}");
}

#[test]
fn a_reply_is_cut_to_what_a_comment_holds() {
    let authors = [burrow_github::fake::author("Sam")];
    let door = Door {
        repo: "sam/box",
        label: "undo",
        authors: &authors,
        what: "this machine's undo",
    };
    let mut gh = Fake::default();
    gh.on("POST", "repos/", vec![ok(201, json!({}), &[])]);
    gh.on("PATCH", "repos/", vec![ok(200, json!({}), &[])]);
    // Two-byte characters, so a cut at the limit falls inside one.
    let long = "é".repeat(MAX_COMMENT);
    door.reply(&mut gh, 3, &long, "completed").unwrap();
    let posted = gh.asked("POST")[0].2.as_ref().unwrap()["body"]
        .as_str()
        .unwrap()
        .to_owned();
    assert!(posted.len() <= MAX_COMMENT, "{}", posted.len());
    assert!(posted.starts_with("éé") && posted.ends_with("past what a comment holds)"));
    assert_eq!(bounded("short"), "short");
    let exact = "x".repeat(MAX_COMMENT);
    assert_eq!(bounded(&exact), exact);
}

#[test]
fn a_reused_login_never_authorizes_an_opener_or_writer() {
    let authors = [burrow_github::fake::author("sam")];
    let door = Door {
        repo: "sam/box",
        label: "probe",
        authors: &authors,
        what: "this machine's probe",
    };
    let spoof = json!({"login":"sam","databaseId":999});
    let history = json!({"totalCount":0,"nodes":[]});
    let original = json!({"author":burrow_github::fake::actor("sam"), "title":"trusted", "body":"trusted", "userContentEdits":history, "timelineItems":history});
    for role in ["opener", "author", "editor", "renamer", "deleter"] {
        let mut issue = Issue {
            number: 7,
            opener: "sam".into(),
            opener_id: Some(authors[0].id),
        };
        let mut text = original.clone();
        match role {
            "opener" => issue.opener_id = Some(999),
            "author" => text["author"] = spoof.clone(),
            "editor" => {
                text["userContentEdits"] = json!({"totalCount":1,"nodes":[{"editor":spoof}]})
            }
            "renamer" => text["timelineItems"] = json!({"totalCount":1,"nodes":[{"actor":spoof}]}),
            _ => {
                text["userContentEdits"] = json!({"totalCount":1,"nodes":[{"editor":burrow_github::fake::actor("sam"),"deletedBy":spoof}]})
            }
        }
        let mut gh = Fake::default();
        gh.on(
            "POST",
            "graphql",
            vec![ok(200, json!({"data":{"repository":{"issue":text}}}), &[])],
        );
        assert!(door.written(&mut gh, &issue).unwrap().is_err(), "{role}");
    }
}
