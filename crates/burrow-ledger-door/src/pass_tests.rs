use std::cell::RefCell;

use burrow_github::fake::{Fake, ok};
use serde_json::{Value, json};

use super::{Cn, Done, Ran, pass};
use crate::Config;

fn config() -> Config {
    Config {
        repo: "sam/box".into(),
        label: "undo".into(),
        authors: vec!["Sam".into()],
        host: "box".into(),
        cn: "/bin/cn".into(),
    }
}

fn issue(n: u64, login: &str, body: &str) -> Value {
    json!({ "number": n, "user": { "login": login }, "title": "undo", "body": body })
}

/// GitHub with `issues` open, each by its opener with nobody else's edits.
fn github(issues: Value) -> Fake {
    let mut gh = Fake::default();
    let said: Vec<_> = issues
        .as_array()
        .unwrap()
        .iter()
        .filter(|i| i["user"]["login"] == "sam")
        .map(|i| {
            ok(
                200,
                json!({ "data": { "repository": { "issue": {
                    "author": { "login": "sam" }, "title": i["title"], "body": i["body"],
                    "userContentEdits": { "totalCount": 0, "nodes": [] },
                    "timelineItems": { "totalCount": 0, "nodes": [] },
                } } } }),
                &[],
            )
        })
        .collect();
    if !said.is_empty() {
        gh.on("POST", "graphql", said);
    }
    gh.on("GET", "repos/sam/box/issues", vec![ok(200, issues, &[])])
        .on(
            "POST",
            "repos/sam/box/issues/",
            vec![ok(201, json!({}), &[])],
        )
        .on(
            "PATCH",
            "repos/sam/box/issues/",
            vec![ok(200, json!({}), &[])],
        );
    gh
}

/// cn, saying `ran` to every run, and keeping what each was asked.
struct FakeCn {
    ran: Ran,
    asked: RefCell<Vec<Vec<String>>>,
}

impl FakeCn {
    fn says(code: i32, stdout: &str, stderr: &str) -> Self {
        Self {
            ran: Ran {
                code: Some(code),
                stdout: stdout.into(),
                stderr: stderr.into(),
            },
            asked: RefCell::new(Vec::new()),
        }
    }
}

impl Cn for FakeCn {
    fn run(&self, args: &[String]) -> Result<Ran, String> {
        self.asked.borrow_mut().push(args.to_vec());
        Ok(self.ran.clone())
    }
}

fn bodies(gh: &Fake) -> Vec<String> {
    gh.asked("POST")
        .into_iter()
        .filter(|a| a.1.starts_with("repos/"))
        .map(|a| a.2.as_ref().unwrap()["body"].as_str().unwrap().to_string())
        .collect()
}

fn closed_as(gh: &Fake) -> Vec<String> {
    gh.asked("PATCH")
        .into_iter()
        .map(|a| {
            a.2.as_ref().unwrap()["state_reason"]
                .as_str()
                .unwrap()
                .to_string()
        })
        .collect()
}

const OPENED: &str = r#"{"change":"01j","pr":12,"url":"https://github.com/sam/web/pull/12","reverts":["01a","01b"],"left":["01c"],"opened":true,"conflicts":false,"recorded":4}
{"gone":["01d"]}
"#;

#[test]
fn an_author_s_undo_runs_and_its_pr_is_the_answer() {
    let mut gh = github(json!([issue(
        7,
        "sam",
        "undo --actor https://claude.ai/code/session_01Bad\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_"
    )]));
    let cn = FakeCn::says(0, OPENED, "");
    let done = pass(&mut gh, &config(), &cn).unwrap();
    assert_eq!(
        done,
        Done {
            answered: vec![7],
            refused: vec![]
        }
    );
    assert_eq!(
        cn.asked.borrow().as_slice(),
        [vec![
            "undo".to_string(),
            "--actor".into(),
            "https://claude.ai/code/session_01Bad".into()
        ]]
    );
    let body = &bodies(&gh)[0];
    assert!(
        body.starts_with("<!-- burrow-ledger-door -->\n`cn undo --actor https://claude.ai/code/session_01Bad` on box:\n"),
        "{body}"
    );
    assert!(
        body.contains("- https://github.com/sam/web/pull/12: reverts 2 changes, opened."),
        "{body}"
    );
    assert!(
        body.contains("Left out") && body.contains("`01c`"),
        "{body}"
    );
    assert!(
        body.contains("already lacks") && body.contains("`01d`"),
        "{body}"
    );
    assert_eq!(closed_as(&gh), ["completed"]);
}

#[test]
fn anyone_else_s_issue_runs_nothing() {
    let mut gh = github(json!([issue(3, "mallory", "undo sam/web#5")]));
    let cn = FakeCn::says(0, OPENED, "");
    let done = pass(&mut gh, &config(), &cn).unwrap();
    assert_eq!(done.refused, [3]);
    assert!(cn.asked.borrow().is_empty());
    assert_eq!(
        bodies(&gh),
        ["<!-- burrow-ledger-door -->\nOnly Sam can ask for an undo here, so nothing was run."]
    );
    assert_eq!(closed_as(&gh), ["not_planned"]);
}

#[test]
fn what_isn_t_one_undo_cn_takes_runs_nothing() {
    for (body, says) in [
        ("undo sam/..#5", "isn't OWNER/REPO"),
        ("undo sam/web#5\nundo sam/web#6", "One undo an issue"),
        (
            "undo sam/web#5; rm -rf /",
            "isn't one undo; ask for one undo",
        ),
        (
            "undo --actor https://evil.example/session_1",
            "isn't a session's link",
        ),
        // Nothing in the body: the title is what it asks.
        ("", "`undo` isn't one undo"),
    ] {
        let mut gh = github(json!([issue(4, "sam", body)]));
        let cn = FakeCn::says(0, OPENED, "");
        let done = pass(&mut gh, &config(), &cn).unwrap();
        assert_eq!(done.refused, [4], "{body}");
        assert!(cn.asked.borrow().is_empty(), "{body}");
        let said = &bodies(&gh)[0];
        assert!(
            said.contains("Nothing was run.") && said.contains(says),
            "{body}: {said}"
        );
    }
}

#[test]
fn cn_s_refusal_is_the_answer_and_github_unavailable_leaves_it_open() {
    let mut gh = github(json!([issue(5, "sam", "undo sam/web#5")]));
    let cn = FakeCn::says(65, "", "cn: change 01x hasn't landed\n");
    let done = pass(&mut gh, &config(), &cn).unwrap();
    assert_eq!(done.refused, [5]);
    assert_eq!(
        cn.asked.borrow().as_slice(),
        [vec!["undo".to_string(), "sam/web#5".into()]]
    );
    let body = &bodies(&gh)[0];
    assert!(
        body.contains("cn refused, so nothing was undone:") && body.contains("hasn't landed"),
        "{body}"
    );
    assert!(!body.contains("stopped"), "{body}");
    assert_eq!(closed_as(&gh), ["not_planned"]);

    let mut gh = github(json!([issue(6, "sam", "undo sam/web#5")]));
    let cn = FakeCn::says(75, "", "GitHub: unavailable\n");
    let err = pass(&mut gh, &config(), &cn).unwrap_err();
    assert!(err.contains("#6: GitHub is unavailable"), "{err}");
    assert!(bodies(&gh).is_empty());
    assert!(closed_as(&gh).is_empty());
}

#[test]
fn a_run_that_stopped_tells_what_it_opened_and_claims_no_refusal() {
    // A session's undo opened one repo's PR, then stopped in the next.
    let opened = OPENED.lines().next().unwrap();
    let unrecorded = r#"{"unrecorded":"https://github.com/sam/api/pull/4","pr":4}"#;
    for (code, stdout) in [
        (Some(1), opened),
        (None, opened),
        (Some(1), ""),
        (Some(1), unrecorded),
    ] {
        let mut gh = github(json!([issue(
            8,
            "sam",
            "undo --actor https://claude.ai/code/session_01Bad"
        )]));
        let cn = FakeCn {
            ran: Ran {
                code,
                stdout: stdout.into(),
                stderr: "cn: sam/api: Server Error\n".into(),
            },
            asked: RefCell::new(Vec::new()),
        };
        let done = pass(&mut gh, &config(), &cn).unwrap();
        assert_eq!(done.refused, [8]);
        let body = &bodies(&gh)[0];
        assert!(
            body.contains("cn stopped before it finished") && body.contains("Server Error"),
            "{body}"
        );
        assert!(body.contains("Asking again finds what it opened"), "{body}");
        assert!(!body.contains("nothing was undone"), "{body}");
        assert_eq!(
            body.contains("- https://github.com/sam/web/pull/12: reverts 2 changes, opened."),
            stdout == opened,
            "{body}"
        );
        assert_eq!(
            body.contains(
                "- https://github.com/sam/api/pull/4: opened, and cn stopped before recording it"
            ),
            stdout == unrecorded,
            "{body}"
        );
        assert_eq!(
            body.contains("after what's above"),
            !stdout.is_empty(),
            "{body}"
        );
        assert_eq!(closed_as(&gh), ["not_planned"]);
    }
}

#[test]
fn an_answer_too_long_for_a_comment_is_cut_and_posted_once() {
    let line = format!("undo {}", "x".repeat(65_500));
    let mut gh = github(json!([issue(9, "sam", &line)]));
    let rows: String = (0..2_000)
        .map(|_| format!("{}\n", OPENED.lines().next().unwrap()))
        .collect();
    let cn = FakeCn::says(0, &rows, "");
    pass(&mut gh, &config(), &cn).unwrap();
    let mut gh2 = github(json!([issue(
        10,
        "sam",
        "undo --actor https://claude.ai/code/session_01Bad"
    )]));
    pass(&mut gh2, &config(), &cn).unwrap();
    for gh in [&gh, &gh2] {
        let said = bodies(gh);
        assert_eq!(said.len(), 1);
        assert!(
            said[0].len() <= burrow_door::MAX_COMMENT,
            "{}",
            said[0].len()
        );
        assert_eq!(closed_as(gh).len(), 1);
    }
    // The long line was refused without running; the long answer ran once.
    assert_eq!(cn.asked.borrow().len(), 1);
}
