//! The head's branch: Renovate takes every branch under its prefix as its
//! own, and calls one it has no update for abandoned, retitling its PR. So
//! a PR whose head is there fails unless Renovate opened it, which its body's
//! mark says; a fork's branch isn't Renovate's to take. No body line passes
//! it: the branch has to move.

use crate::*;

fn rust() -> Vec<serde_json::Value> {
    vec![change("modified", "src/main.rs", 1, 1)]
}

/// The end of a body Renovate writes.
const RENOVATES: &str = "Updates nix.\n\n---\n\nThis PR has been generated by [Mend Renovate CLI](https://example).\n<!--renovate-debug:eyJjcmVhdGVkSW5WZXIiOiI0NCJ9-->\n";

// The PR that met it: a job's branch named for the area it changed.
#[test]
fn a_jobs_branch_under_renovates_prefix() {
    let c = case(rust())
        .branch("renovate/rate-limit-mid-run")
        .body("Fixes #1.\n");
    let error = fails(&c, "branch");
    assert!(error.contains("Renovate didn't open it"), "{error}");
    let o = c.run();
    let p = o
        .posted
        .iter()
        .find(|p| p.status.context == "house/branch (#7)")
        .unwrap();
    assert!(!p.status.description.contains("rate-limit"), "{p:?}");
    assert!(!o.out.contains("rate-limit"), "{}", o.out);
    // A reason in the body doesn't move the branch.
    fails(
        &c.clone()
            .body("Why a branch: it is about renovate after all\n"),
        "branch",
    );
}

#[test]
fn renovates_own() {
    passes(
        &case(rust())
            .branch("renovate/nix-lock-file-maintenance")
            .body(RENOVATES),
    );
    passes(
        &case(rust())
            .branch("renovate/x")
            .body(&RENOVATES.replace('\n', "\r\n")),
    );
}

#[test]
fn elsewhere() {
    for branch in [
        "renovate-run/x",
        "jobs/renovate",
        "deps/renovate/x",
        "tools/plain",
    ] {
        passes(&case(rust()).branch(branch));
    }
}

#[test]
fn a_forks() {
    let mut c = case(rust()).branch("renovate/x");
    c.fork = Fork::Yes;
    passes(&c);
}

// Renovate's mark taken out of the body (an edit) fails it again.
#[test]
fn edited() {
    let o = case(rust())
        .branch("renovate/x")
        .body(RENOVATES)
        .change(
            1,
            Change {
                body: Some("Mine now.\n"),
                ..Change::default()
            },
        )
        .run();
    assert_eq!(o.result, Ok(true));
    assert_eq!(
        said(&o.posted, "branch"),
        [
            ("4ead".into(), "success", "this run"),
            ("4ead".into(), "failure", "this run")
        ]
    );
}
