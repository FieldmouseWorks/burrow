//! File size: the line limit is a backstop, not the measure. A non-test code
//! file pushed across the limit (over it at the head, and at or under it or
//! absent at the merge base) needs `Why not split:` (or a standing waiver);
//! growing an unwaived file already over the limit at the merge base fails and
//! passes only via a standing waiver in `file-size-allow`, never a body line.
//! Current length is always read at the head, prior length at the merge base,
//! never the base's tip (which may have moved on).

use crate::*;

const REASON: &str = "Why not split: one table, generated by hand from the spec.";

/// Asserts a PR fails `file-size` because it grew an unwaived file already
/// over the limit (so `Why not split:` does not pass it).
#[track_caller]
fn fails_already_over(c: &Case) -> String {
    let o = c.run();
    let errors = o.errors();
    assert!(
        errors.len() == 1
            && errors[0].starts_with("::error title=File size::")
            && errors[0].contains("file-size-allow"),
        "expected already-over failure: {:?}\n{}",
        o.result,
        o.out
    );
    if c.fork == Fork::No {
        assert_eq!(o.result, Ok(true), "{}", o.out);
        status(&o.posted, &["file-size"], &c.rules());
    } else {
        assert_eq!(o.result, Ok(false), "{}", o.out);
        assert!(o.posted.is_empty(), "{:#?}", o.posted);
    }
    errors[0].to_owned()
}

// Pushing a non-test code file across the limit (at or under it, absent,
// non-code or test at the merge base) fails without `Why not split:` and
// passes with it.
#[test]
fn crossing() {
    let (long, short, at_limit) = (long(), "x\n".repeat(10), "x\n".repeat(LINES));
    for c in [
        case(vec![change("modified", "src/big.rs", 20, 5)])
            .tree("4ead", "src/big.rs", &long)
            .tree("3e7b", "src/big.rs", &short),
        // Exactly at the limit before, one line past it at the head: crossed.
        case(vec![change("modified", "src/big.rs", 2, 1)])
            .tree("4ead", "src/big.rs", &long)
            .tree("3e7b", "src/big.rs", &at_limit),
        case(vec![change("added", "src/new.ts", LINES as u64 + 1, 0)]),
        // A copy is a new file, whatever its diff counts.
        case(vec![from(change("copied", "src/b.rs", 0, 0), "src/a.rs")])
            .tree("4ead", "src/b.rs", &long),
        case(vec![from(change("renamed", "src/b.rs", 3, 1), "src/a.rs")])
            .tree("4ead", "src/b.rs", &long)
            .tree("3e7b", "src/a.rs", &at_limit),
        // Renamed from a test file into non-test code (even with 0 lines
        // changed): had 0 non-test lines.
        case(vec![from(
            change("renamed", "src/b.rs", 0, 0),
            "tests/a.rs",
        )])
        .tree("4ead", "src/b.rs", &long)
        .tree("3e7b", "tests/a.rs", &long),
        // Renamed from non-code into code (even with 0 lines changed): had 0
        // code lines.
        case(vec![from(
            change("renamed", "src/b.rs", 0, 0),
            "docs/a.txt",
        )])
        .tree("4ead", "src/b.rs", &long)
        .tree("3e7b", "docs/a.txt", &long),
        case(vec![
            change("modified", "modules/x.nix", 5, 0),
            change("modified", "tools/x.py", 5, 0),
        ])
        .tree("4ead", "modules/x.nix", &long)
        .tree("3e7b", "modules/x.nix", &short)
        .tree("4ead", "tools/x.py", &long)
        .tree("3e7b", "tools/x.py", &short),
        // A script with no extension is code by its shebang.
        case(vec![change("modified", "bin/tool", 5, 0)])
            .tree("4ead", "bin/tool", &format!("#!/bin/sh\n{long}"))
            .tree("3e7b", "bin/tool", "#!/bin/sh\n"),
    ] {
        let err = fails(&c, "file-size");
        assert!(err.contains("backstop"), "{err}");
        passes(&c.clone().body(REASON));
    }
}

// Growing an unwaived file that was already over the limit at the merge base
// fails, and `Why not split:` does not pass it: only a standing waiver in
// `file-size-allow` (or splitting / not growing it) does.
#[test]
fn already_over_unwaived_and_grown() {
    let over = "x\n".repeat(LINES + 1);
    let longer = "x\n".repeat(LINES + 5);
    for c in [
        case(vec![change("modified", "src/big.rs", 5, 1)])
            .tree("4ead", "src/big.rs", &longer)
            .tree("3e7b", "src/big.rs", &over),
        case(vec![from(change("renamed", "src/b.rs", 5, 1), "src/a.rs")])
            .tree("4ead", "src/b.rs", &longer)
            .tree("3e7b", "src/a.rs", &over),
        case(vec![change("modified", "bin/tool", 5, 1)])
            .tree("4ead", "bin/tool", &format!("#!/bin/sh\n{longer}"))
            .tree("3e7b", "bin/tool", &format!("#!/bin/sh\n{over}")),
        // Both an already-over unwaived file and a crossing file: still fails
        // even when the body gives `Why not split:`.
        case(vec![
            change("modified", "src/big.rs", 5, 1),
            change("modified", "src/crossed.rs", 10, 0),
        ])
        .tree("4ead", "src/big.rs", &longer)
        .tree("3e7b", "src/big.rs", &over)
        .tree("4ead", "src/crossed.rs", &over)
        .tree("3e7b", "src/crossed.rs", &"x\n".repeat(LINES)),
    ] {
        fails_already_over(&c);
        fails_already_over(&c.clone().body(REASON));
    }
}

// Prior length is read at the merge base (`3e7b`), never the base tip (`ba5e`):
// a moved base cannot flip crossing into already-over or vice versa.
#[test]
fn prior_length_uses_merge_base_not_base_tip() {
    let (over, longer, short) = (
        "x\n".repeat(LINES + 1),
        "x\n".repeat(LINES + 5),
        "x\n".repeat(LINES),
    );
    // Merge base was at the limit (`short`), base tip moved past it (`over`):
    // this PR pushed it across from the merge base, so `Why not split:` passes.
    let crossed_from_merge_base = case(vec![change("modified", "src/big.rs", 5, 0)])
        .tree("4ead", "src/big.rs", &longer)
        .tree("3e7b", "src/big.rs", &short)
        .tree("ba5e", "src/big.rs", &over);
    fails(&crossed_from_merge_base, "file-size");
    passes(&crossed_from_merge_base.body(REASON));

    // Merge base was already over (`over`), base tip later shrank it (`short`):
    // this PR grew an already-over file from its merge base, so `Why not split:`
    // does not pass it.
    let over_at_merge_base = case(vec![change("modified", "src/big.rs", 5, 1)])
        .tree("4ead", "src/big.rs", &longer)
        .tree("3e7b", "src/big.rs", &over)
        .tree("ba5e", "src/big.rs", &short);
    fails_already_over(&over_at_merge_base);
    fails_already_over(&over_at_merge_base.body(REASON));
}

// Shrinking an over-limit file, keeping its length, or adding only inline
// `#[cfg(test)]` lines to an already-over Rust file passes; so does a file
// just at the limit, one that isn't code, and one a tool generates.
#[test]
fn already_over_and_not_grown() {
    let long = long();
    let o = passes(
        &case(vec![
            change("modified", "src/big.ts", 5, 20),
            change("modified", "src/even.ts", 5, 5),
        ])
        .tree("4ead", "src/big.ts", &long)
        .tree("3e7b", "src/big.ts", &long),
    );
    assert!(
        !o.calls.iter().any(|c| c.starts_with("content")),
        "{:?}",
        o.calls
    );
    // Already over the limit in production code, and the PR adds only inline
    // `#[cfg(test)]` lines: non-test code did not grow, so it passes.
    let prod = "fn prod() {}\n".repeat(LINES + 5);
    let before_tests =
        format!("{prod}\n#[cfg(test)]\nmod tests {{\n    #[test]\n    fn t1() {{}}\n}}\n");
    let with_more_tests = format!(
        "{prod}\n#[cfg(test)]\nmod tests {{\n    #[test]\n    fn t1() {{}}\n    #[test]\n    fn t2() {{}}\n}}\n"
    );
    passes(
        &case(vec![change("modified", "src/big.rs", 2, 0)])
            .tree("4ead", "src/big.rs", &with_more_tests)
            .tree("3e7b", "src/big.rs", &before_tests),
    );
    // At the limit in production code, replacing a `#[cfg(test)]` line with a
    // production line (added == removed, or even added < removed) crosses the
    // non-test code limit and must fail `file-size`.
    let at_limit_prod = "fn prod() {}\n".repeat(LINES);
    let at_limit_with_tests = format!(
        "{at_limit_prod}#[cfg(test)]\nmod tests {{\n    #[test]\n    fn t1() {{}}\n    #[test]\n    fn t2() {{}}\n}}\n"
    );
    let crossed_swapped_equal = format!(
        "{at_limit_prod}fn extra() {{}}\n#[cfg(test)]\nmod tests {{\n    #[test]\n    fn t1() {{}}\n    #[test]\n}}\n"
    );
    fails(
        &case(vec![change("modified", "src/swap.rs", 1, 1)])
            .tree("4ead", "src/swap.rs", &crossed_swapped_equal)
            .tree("3e7b", "src/swap.rs", &at_limit_with_tests),
        "file-size",
    );
    let crossed_swapped_fewer = format!(
        "{at_limit_prod}fn extra() {{}}\n#[cfg(test)]\nmod tests {{\n    #[test]\n    fn t1() {{}}\n}}\n"
    );
    fails(
        &case(vec![change("modified", "src/swap_shrink.rs", 1, 2)])
            .tree("4ead", "src/swap_shrink.rs", &crossed_swapped_fewer)
            .tree("3e7b", "src/swap_shrink.rs", &at_limit_with_tests),
        "file-size",
    );
    passes(&case(vec![change("modified", "src/big.rs", 20, 5)]).tree(
        "4ead",
        "src/big.rs",
        &"x\n".repeat(LINES),
    ));
    for path in [
        "docs/GAME_DATA.md",
        "data/items.json",
        "Cargo.lock",
        "server/client/src/generated/api.ts",
        "generated/api.rs",
        "web/app.generated.ts",
        "src/schema.gen.go",
        "proto/x_pb2.py",
        "web/vendor.min.js",
        "bin/data",
    ] {
        passes(
            &case(vec![change("modified", path, 20, 5)])
                .tree("4ead", path, &long)
                .tree("3e7b", path, &long),
        );
    }
}

// The last line counts, with or without a newline after it.
#[test]
fn last_line() {
    let lines = "x\n".repeat(LINES);
    let c = |content: &str| {
        case(vec![change("modified", "src/big.rs", 20, 5)])
            .tree("4ead", "src/big.rs", content)
            .tree("3e7b", "src/big.rs", &"x\n".repeat(LINES - 15))
    };
    fails(&c(&format!("{lines}x")), "file-size");
    passes(&c(&format!("{}x", "x\n".repeat(LINES - 1))));
    passes(&c(""));
}

// A file renamed with no lines changed was already there: it didn't grow.
// Renaming an extensionless non-code file to a code suffix crosses into code
// and fails `file-size`, whereas renaming an extensionless script with a
// shebang was already code and passes.
#[test]
fn renamed() {
    passes(
        &case(vec![from(change("renamed", "src/b.rs", 0, 0), "src/a.rs")]).tree(
            "4ead",
            "src/b.rs",
            &long(),
        ),
    );
    fails(
        &case(vec![from(change("renamed", "src/notes.rs", 0, 0), "notes")])
            .tree("4ead", "src/notes.rs", &long())
            .tree("3e7b", "notes", &long()),
        "file-size",
    );
    let script = format!("#!/usr/bin/env python3\n{}", long());
    passes(
        &case(vec![from(
            change("renamed", "src/tool.py", 0, 0),
            "bin/tool",
        )])
        .tree("4ead", "src/tool.py", &script)
        .tree("3e7b", "bin/tool", &script),
    );
}

// A repo can set its own limit.
#[test]
fn its_own_limit() {
    let mut c = case(vec![change("modified", "src/x.rs", 20, 5)])
        .tree("4ead", "src/x.rs", &"x\n".repeat(501))
        .tree("3e7b", "src/x.rs", &"x\n".repeat(486));
    c.lines = 500;
    fails(&c, "file-size");
}

// No answer for either the head or the merge base's content is no verdict.
#[test]
fn no_answer() {
    let o = case(vec![change("modified", "src/big.rs", 20, 5)])
        .body(REASON)
        .tree("3e7b", "src/big.rs", &long())
        .unread("4ead", "src/big.rs")
        .run();
    assert!(o.result.is_err() && o.posted.is_empty(), "{}", o.out);

    let o = case(vec![change("modified", "src/big.rs", 20, 5)])
        .body(REASON)
        .tree("4ead", "src/big.rs", &long())
        .unread("3e7b", "src/big.rs")
        .run();
    assert!(o.result.is_err() && o.posted.is_empty(), "{}", o.out);
}

