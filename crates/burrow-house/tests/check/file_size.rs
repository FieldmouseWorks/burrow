//! File size: a code file the PR leaves longer than it found it, and past the
//! limit at its head, whether it grew past it here or was past it already.
//! Its length is read at the head, never the merge base or the base's tip.

use crate::*;

const REASON: &str = "Why not split: one table, generated by hand from the spec.";

#[test]
fn grown() {
    let (long, short) = (long(), "x\n".repeat(10));
    for c in [
        case(vec![change("modified", "src/big.rs", 20, 5)])
            .tree("4ead", "src/big.rs", &long)
            .tree("3e7b", "src/big.rs", &short),
        case(vec![change("modified", "src/big.rs", 2, 1)]).tree("4ead", "src/big.rs", &long),
        case(vec![change("added", "src/new.ts", LINES as u64 + 1, 0)]),
        // A copy is a new file, whatever its diff counts.
        case(vec![from(change("copied", "src/b.rs", 0, 0), "src/a.rs")])
            .tree("4ead", "src/b.rs", &long),
        case(vec![from(change("renamed", "src/b.rs", 3, 1), "src/a.rs")])
            .tree("4ead", "src/b.rs", &long),
        case(vec![
            change("modified", "modules/x.nix", 5, 0),
            change("modified", "tests/x.py", 5, 0),
        ])
        .tree("4ead", "modules/x.nix", &long)
        .tree("4ead", "tests/x.py", &long),
        // A script with no extension is code by its shebang.
        case(vec![change("modified", "bin/tool", 5, 0)])
            .tree("4ead", "bin/tool", &format!("#!/bin/sh\n{long}"))
            .tree("3e7b", "bin/tool", "#!/bin/sh\n"),
    ] {
        fails(&c, "file-size");
        passes(&c.clone().body(REASON));
    }
}

// Shrinking it, or keeping its length, passes, and isn't read; so does a
// file just at the limit, one that isn't code, and one a tool generates.
#[test]
fn not_grown() {
    let long = long();
    let o = passes(
        &case(vec![
            change("modified", "src/big.rs", 5, 20),
            change("modified", "src/even.rs", 5, 5),
        ])
        .tree("4ead", "src/big.rs", &long),
    );
    assert!(
        !o.calls.iter().any(|c| c.starts_with("content")),
        "{:?}",
        o.calls
    );
    passes(&case(vec![change("modified", "src/big.rs", 20, 5)]).tree(
        "4ead",
        "src/big.rs",
        &"x\n".repeat(LINES),
    ));
    for path in [
        "docs/GAME_DATA.md",
        "data/items.json",
        "Cargo.lock",
        "server/client/src/generated/api.ts",
        "generated/api.rs",
        "web/app.generated.ts",
        "src/schema.gen.go",
        "proto/x_pb2.py",
        "web/vendor.min.js",
        "bin/data",
    ] {
        passes(
            &case(vec![change("modified", path, 20, 5)])
                .tree("4ead", path, &long)
                .tree("3e7b", path, &long),
        );
    }
}

// The last line counts, with or without a newline after it.
#[test]
fn last_line() {
    let lines = "x\n".repeat(LINES);
    let c = |content: &str| {
        case(vec![change("modified", "src/big.rs", 20, 5)]).tree("4ead", "src/big.rs", content)
    };
    fails(&c(&format!("{lines}x")), "file-size");
    passes(&c(&format!("{}x", "x\n".repeat(LINES - 1))));
    passes(&c(""));
}

// A file renamed with no lines changed was already there: it didn't grow.
#[test]
fn renamed() {
    passes(
        &case(vec![from(change("renamed", "src/b.rs", 0, 0), "src/a.rs")]).tree(
            "4ead",
            "src/b.rs",
            &long(),
        ),
    );
}

// A repo can set its own limit.
#[test]
fn its_own_limit() {
    let mut c = case(vec![change("modified", "src/x.rs", 20, 5)]).tree(
        "4ead",
        "src/x.rs",
        &"x\n".repeat(501),
    );
    c.lines = 500;
    fails(&c, "file-size");
}

// No answer for its content is no verdict.
#[test]
fn no_answer() {
    let o = case(vec![change("modified", "src/big.rs", 20, 5)])
        .body(REASON)
        .tree("3e7b", "src/big.rs", &long())
        .unread("4ead", "src/big.rs")
        .run();
    assert!(o.result.is_err() && o.posted.is_empty(), "{}", o.out);
}

#[test]
fn fork() {
    let mut c =
        case(vec![change("modified", "src/big.rs", 20, 5)]).tree("4ead", "src/big.rs", &long());
    c.fork = Fork::Yes;
    fails(&c, "file-size");
}
